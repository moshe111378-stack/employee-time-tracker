const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM}=require('jsdom');
const fixture=process.env.SYNC_FIXTURES;
const dom=new JSDOM(fs.readFileSync(path.join(fixture,'reports.html'),'utf8'),{url:'https://test.invalid/admin/reports',runScripts:'dangerously'});
const w=dom.window,d=w.document;
assert.equal(d.getElementById('sh').textContent,'12:30');
assert.equal(d.getElementById('sp').textContent,'₪420.00');
assert.equal(d.getElementById('unpricedNotice').hidden,false);
w.setPeriod('week');
assert.equal(d.getElementById('sh').textContent,'8:30');
assert.equal(d.getElementById('sp').textContent,'₪340.00');
assert.equal(d.getElementById('sw').textContent,'1');
assert.equal(d.getElementById('unpricedNotice').hidden,true);
assert.equal(d.getElementById('partialPeriodNotice').hidden,true);
assert.equal(d.querySelector('.report-card').hidden,false);
console.log('PASS period filters use actual work dates, including manual hours on a year-long event');
w.setPeriod('month');
assert.equal(d.getElementById('sh').textContent,'10:30');
assert.equal(d.getElementById('sp').textContent,'₪420.00');
assert.equal(d.getElementById('partialPeriodNotice').hidden,false);
assert.equal([...d.querySelectorAll('.partial-entry')].filter(x=>!x.hidden).length,1);
console.log('PASS partially overlapping totals remain explicit and are never prorated silently');
d.getElementById('rq').value='no such event';w.filterReports();
assert.equal(d.getElementById('sh').textContent,'0:00');
assert.equal(d.getElementById('sp').textContent,'₪0.00');
assert.equal(d.querySelector('.report-card').hidden,true);
console.log('PASS search and filtered summaries agree');
dom.window.close();
const formDom=new JSDOM(fs.readFileSync(path.join(fixture,'manual-form.html'),'utf8'),{url:'https://test.invalid/admin/event/1/hours',runScripts:'dangerously'});
const f=formDom.window,doc=f.document;
const hours=doc.querySelector('[name="hours_1"]');hours.value='8';hours.dispatchEvent(new f.Event('input',{bubbles:true}));
const rangeSubmit=new f.Event('submit',{bubbles:true,cancelable:true});doc.getElementById('hoursPeriodForm').dispatchEvent(rangeSubmit);
assert.equal(rangeSubmit.defaultPrevented,true);assert.equal(hours.value,'8');assert.equal(doc.getElementById('hoursPeriodNotice').hidden,false);
console.log('PASS changing the period does not discard unsaved hours');
formDom.window.close();
